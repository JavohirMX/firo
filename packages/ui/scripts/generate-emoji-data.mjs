// Generates packages/ui/src/emoji/emojiData.generated.ts from pinned Unicode
// files. Run by hand; the build never fetches anything.
//
//   node packages/ui/scripts/generate-emoji-data.mjs \
//     <emoji-test.txt> <cldr common/annotations/en.xml> \
//     <cldr common/annotationsDerived/en.xml>
//
// Inputs and their hashes are recorded in src/emoji/PROVENANCE.md.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [testPath, annPath, derivedPath] = process.argv.slice(2);
if (!testPath || !annPath || !derivedPath) {
  console.error("usage: generate-emoji-data.mjs <emoji-test> <annotations> <derived>");
  process.exit(1);
}
const sha = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");
const strip = (s) => s.replace(/\uFE0F/g, "");

const keywords = new Map();
for (const p of [annPath, derivedPath]) {
  const xml = readFileSync(p, "utf8");
  for (const m of xml.matchAll(/<annotation cp="([^"]+)">([^<]*)<\/annotation>/g)) {
    const key = strip(m[1]);
    if (!keywords.has(key)) {
      keywords.set(key, m[2].split("|").map((k) => k.trim()).filter(Boolean));
    }
  }
}

const SKIN = /[\u{1F3FB}-\u{1F3FF}]/u;
const categories = [];
let current = null;
let version = "";
for (const line of readFileSync(testPath, "utf8").split("\n")) {
  const v = line.match(/^# Version: (.+)/);
  if (v) version = v[1].trim();
  const g = line.match(/^# group: (.+)/);
  if (g) {
    current = g[1].trim() === "Component" ? null : { name: g[1].trim(), items: [] };
    if (current) categories.push(current);
    continue;
  }
  if (!current) continue;
  const m = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/);
  if (!m) continue;
  const [, char, name] = m;
  if (SKIN.test(char)) continue;
  const kw = (keywords.get(strip(char)) ?? []).filter((k) => k !== name);
  current.items.push([char, name, kw.join(" ")]);
}

const seen = new Set();
for (const c of categories) {
  c.items = c.items.filter(([ch]) => (seen.has(ch) ? false : seen.add(ch)));
}
const total = categories.reduce((n, c) => n + c.items.length, 0);
const out = `// GENERATED by packages/ui/scripts/generate-emoji-data.mjs. Do not edit.
// Unicode emoji ${version} (emoji-test.txt) with CLDR English annotations.
// Licence: see ./LICENSE-UNICODE.txt. Provenance: see ./PROVENANCE.md.
// Skin-tone modifier sequences are excluded by design.

export type EmojiEntry = readonly [
  char: string,
  name: string,
  keywords: string,
];

export type EmojiCategory = {
  readonly id: string;
  readonly name: string;
  readonly emoji: readonly EmojiEntry[];
};

export const EMOJI_UNICODE_VERSION = ${JSON.stringify(version)};

export const EMOJI_CATEGORIES: readonly EmojiCategory[] = ${JSON.stringify(
  categories.map((c) => ({
    id: c.name.toLowerCase().replace(/[^a-z]+/g, "-").replace(/^-|-$/g, ""),
    name: c.name,
    emoji: c.items,
  })),
  null,
  1,
)};
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "../src/emoji/emojiData.generated.ts"), out);
console.log(JSON.stringify({ version, categories: categories.map((c) => [c.name, c.items.length]), total, inputs: { test: sha(testPath), ann: sha(annPath), derived: sha(derivedPath) } }));
